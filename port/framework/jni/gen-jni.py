"""
JNI methods for natives written against Husk's interpreter (shim.h): reads a native table from a
C file, { "name", "(sig)R", fn }, and writes a C file that includes it and, for each native, the
JNI method that runs it, plus a function registering them all on their class.

    gen-jni.py natives.c TABLE CLASS REGISTER out.c

  e.g. gen-jni.py gfx.c k_gfx husk/Gfx husk_register_gfx gfx_jni.c
"""
import re
import sys

src, table, cls, register, out = sys.argv[1:]
text = open(src).read()
start = text.index(table + "[]")
body = text[start:text.index("};", start)]
natives = re.findall(r'\{\s*"(\w+)",\s*"([^"]+)",\s*(\w+)\s*\}', body)

JNI = {"I": "jint", "J": "jlong", "F": "jfloat", "D": "jdouble", "Z": "jboolean", "B": "jbyte",
       "S": "jshort", "C": "jchar", "V": "void", "L": "jobject", "[": "jobject"}
SLOT = {"I": "i", "J": "j", "F": "f", "D": "d", "Z": "z", "B": "b", "S": "s", "C": "c"}


def params(sig):
    """the descriptor letters of a signature's parameters, and its return's"""
    out, i = [], 1
    while sig[i] != ")":
        c = sig[i]
        if c == "[":
            while sig[i] == "[":
                i += 1
            if sig[i] == "L":
                i = sig.index(";", i)
            out.append("[")
        elif c == "L":
            i = sig.index(";", i)
            out.append("L")
        else:
            out.append(c)
        i += 1
    ret = sig[i + 1]
    return out, "L" if ret == "[" else ret


w = open(out, "w")
w.write(f"/* generated by port/framework/jni/gen-jni.py from {src}'s {table}: the JNI methods of {cls} */\n")
w.write(f'#include "{src}"\n\n')
# HUSK_FRAME_STATS: each native's calls and time, for <table>_report (the costliest, to the log)
N = len(natives)
w.write("#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n#include <time.h>\n")
w.write(f"static int64_t jt_ns_{table}[{N}], jt_n_{table}[{N}];\nstatic int jt_on_{table} = -1;\n")
w.write(f"static const char *const jt_name_{table}[{N}] = {{ " + ", ".join(f'"{n}"' for n, _, _ in natives) + " };\n")
w.write(f"static inline int64_t jt_now_{table}(void) {{ if (jt_on_{table} < 0) jt_on_{table} = getenv(\"HUSK_FRAME_STATS\") != NULL; "
        f"if (!jt_on_{table}) return 0; struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t); return (int64_t)t.tv_sec * 1000000000 + t.tv_nsec; }}\n")
w.write(f"static void jt_tick_{table}(int i, int64_t t0) {{ if (t0) {{ jt_ns_{table}[i] += jt_now_{table}() - t0; jt_n_{table}[i]++; }} }}\n")
w.write(f"""/* the costliest natives since the last report, per frame, to the log; then zero */
void {table}_report(long frames);
void {table}_report(long frames)
{{
    if (frames < 1) frames = 1;
    char line[1024]; size_t o = 0;
    o += (size_t)snprintf(line + o, sizeof line - o, "natives per frame:");
    for (int k = 0; k < 10; k++) {{
        int best = -1;
        for (int i = 0; i < {N}; i++) if (jt_ns_{table}[i] > 0 && (best < 0 || jt_ns_{table}[i] > jt_ns_{table}[best])) best = i;
        if (best < 0) break;
        if (o < sizeof line) o += (size_t)snprintf(line + o, sizeof line - o, " %s %.1fx %.2fms", jt_name_{table}[best], (double)jt_n_{table}[best] / frames, jt_ns_{table}[best] / 1e6 / frames);
        jt_ns_{table}[best] = -jt_ns_{table}[best];
    }}
    for (int i = 0; i < {N}; i++) {{ jt_ns_{table}[i] = 0; jt_n_{table}[i] = 0; }}
    tl_log_line("FrameStats: %s", line);
}}
""")
for idx, (name, sig, fn) in enumerate(natives):
    ps, ret = params(sig)
    # ART calls natives the AAPCS64 way: a parameter past the registers takes a whole 8-byte stack slot, where Apple's
    # arm64 ABI packs a narrower one to its own size; so those are declared 8 bytes wide here and narrowed in the body
    gpr, fpr, stacked = 2, 0, set()
    for k, p in enumerate(ps):
        if p in "FD":
            fpr += 1
            if fpr > 8: stacked.add(k)
        else:
            gpr += 1
            if gpr > 8: stacked.add(k)
    wide = lambda k, p: ("uint64_t" if p == "F" else "jlong" if p in "IZBSC" else JNI[p]) if k in stacked else JNI[p]
    args = "".join(f", {wide(k, p)} p{k}" for k, p in enumerate(ps))
    w.write(f"static {JNI[ret]} J_{fn}(JNIEnv *env, jclass cls{args})\n{{\n")
    w.write(f"    (void)cls;\n    int64_t jt0 = jt_now_{table}();\n    shim_call c;\n    shim_begin(&c, env);\n")
    w.write(f"    jvalue a[{max(len(ps), 1)}] = {{{{0}}}};\n")
    for k, p in enumerate(ps):
        if p in ("L", "["):
            w.write(f"    a[{k}].l = (jobject)shim_in(p{k}, '{p}');\n")
        elif k in stacked and p == "F":
            w.write(f"    {{ uint32_t lo = (uint32_t)p{k}; memcpy(&a[{k}].f, &lo, 4); }}\n")
        elif k in stacked and p in "IZBSC":
            w.write(f"    a[{k}].{SLOT[p]} = ({JNI[p]})p{k};\n")
        else:
            w.write(f"    a[{k}].{SLOT[p]} = p{k};\n")
    w.write("    jvalue r = {0};\n")
    w.write(f"    bool ok = {fn}(NULL, a, &r);\n")
    tick = f"    jt_tick_{table}({idx}, jt0);\n"
    if ret == "V":
        w.write("    (void)ok; (void)r;\n    shim_end(&c);\n" + tick + "}\n\n")
    elif ret == "L":
        w.write("    jobject o = ok ? shim_out((jobj *)r.l) : NULL;\n    shim_end(&c);\n" + tick + "    return o;\n}\n\n")
    else:
        w.write(f"    shim_end(&c);\n" + tick + f"    return ok ? r.{SLOT[ret]} : 0;\n}}\n\n")
w.write(f"static const JNINativeMethod k_jni_{table}[] = {{\n")
for name, sig, fn in natives:
    w.write(f'    {{ "{name}", "{sig}", (void *)J_{fn} }},\n')
w.write("};\n\n")
w.write(f"bool {register}(JNIEnv *env);\nbool {register}(JNIEnv *env)\n{{\n")
w.write(f'    return shim_register(env, "{cls}", k_jni_{table}, (int)(sizeof k_jni_{table} / sizeof *k_jni_{table}));\n}}\n')
w.close()
print(f"{out}: {len(natives)} natives of {cls}")
