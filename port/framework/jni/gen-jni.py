"""
JNI methods for natives written against Husk's interpreter (shim.h): reads a native table from a
C file, { "name", "(sig)R", fn }, and writes a C file that includes it and, for each native, the
JNI method that runs it, plus a function registering them all on their class.

    gen-jni.py natives.c TABLE CLASS REGISTER out.c

  e.g. gen-jni.py gfx.c k_gfx husk/Gfx husk_register_gfx gfx_jni.c
"""
import re
import sys

src, table, cls, register, out = sys.argv[1:]
text = open(src).read()
start = text.index(table + "[]")
body = text[start:text.index("};", start)]
natives = re.findall(r'\{\s*"(\w+)",\s*"([^"]+)",\s*(\w+)\s*\}', body)

JNI = {"I": "jint", "J": "jlong", "F": "jfloat", "D": "jdouble", "Z": "jboolean", "B": "jbyte",
       "S": "jshort", "C": "jchar", "V": "void", "L": "jobject", "[": "jobject"}
SLOT = {"I": "i", "J": "j", "F": "f", "D": "d", "Z": "z", "B": "b", "S": "s", "C": "c"}


def params(sig):
    """the descriptor letters of a signature's parameters, and its return's"""
    out, i = [], 1
    while sig[i] != ")":
        c = sig[i]
        if c == "[":
            while sig[i] == "[":
                i += 1
            if sig[i] == "L":
                i = sig.index(";", i)
            out.append("[")
        elif c == "L":
            i = sig.index(";", i)
            out.append("L")
        else:
            out.append(c)
        i += 1
    ret = sig[i + 1]
    return out, "L" if ret == "[" else ret


w = open(out, "w")
w.write(f"/* generated by port/framework/jni/gen-jni.py from {src}'s {table}: the JNI methods of {cls} */\n")
w.write(f'#include "{src}"\n\n')
for name, sig, fn in natives:
    ps, ret = params(sig)
    args = "".join(f", {JNI[p]} p{k}" for k, p in enumerate(ps))
    w.write(f"static {JNI[ret]} J_{fn}(JNIEnv *env, jclass cls{args})\n{{\n")
    w.write("    (void)cls;\n    shim_call c;\n    shim_begin(&c, env);\n")
    w.write(f"    jvalue a[{max(len(ps), 1)}] = {{{{0}}}};\n")
    for k, p in enumerate(ps):
        if p in ("L", "["):
            w.write(f"    a[{k}].l = (jobject)shim_in(p{k}, '{p}');\n")
        else:
            w.write(f"    a[{k}].{SLOT[p]} = p{k};\n")
    w.write("    jvalue r = {0};\n")
    w.write(f"    bool ok = {fn}(NULL, a, &r);\n")
    if ret == "V":
        w.write("    (void)ok; (void)r;\n    shim_end(&c);\n}\n\n")
    elif ret == "L":
        w.write("    jobject o = ok ? shim_out((jobj *)r.l) : NULL;\n    shim_end(&c);\n    return o;\n}\n\n")
    else:
        w.write(f"    shim_end(&c);\n    return ok ? r.{SLOT[ret]} : 0;\n}}\n\n")
w.write(f"static const JNINativeMethod k_jni_{table}[] = {{\n")
for name, sig, fn in natives:
    w.write(f'    {{ "{name}", "{sig}", (void *)J_{fn} }},\n')
w.write("};\n\n")
w.write(f"bool {register}(JNIEnv *env);\nbool {register}(JNIEnv *env)\n{{\n")
w.write(f'    return shim_register(env, "{cls}", k_jni_{table}, (int)(sizeof k_jni_{table} / sizeof *k_jni_{table}));\n}}\n')
w.close()
print(f"{out}: {len(natives)} natives of {cls}")
