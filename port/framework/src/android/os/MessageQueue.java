    synchronized boolean enqueue(Message m, long when) {
        if (quitting) return false;
        m.when = when;
        if (head == null || when < head.when) { m.next = head; head = m; }
        else { Message p = head; while (p.next != null && p.next.when <= when) p = p.next; m.next = p.next; p.next = m; }
        notifyAll();
        if (mMain) husk.Native.wake();
        return true;
    }
    synchronized void remove(Handler h, Runnable r, int what, boolean byWhat, Object token) {
        Message prev = null, p = head;
        while (p != null) {
            boolean hit = p.target == h && (byWhat ? p.what == what && (token == null || p.obj == token) : (r == null || p.callback == r) && (token == null || p.obj == token));
            if (byWhat == false && r == null && token == null) hit = p.target == h;
            if (hit) { if (prev == null) head = p.next; else prev.next = p.next; p = p.next; }
            else { prev = p; p = p.next; }
        }
    }
    synchronized boolean has(Handler h, int what) { for (Message p = head; p != null; p = p.next) if (p.target == h && p.what == what) return true; return false; }
    synchronized boolean has(Handler h, int what, Object obj, boolean equal) {
        for (Message p = head; p != null; p = p.next)
            if (p.target == h && p.what == what && (obj == null || (equal ? obj.equals(p.obj) : p.obj == obj))) return true;
        return false;
    }
    synchronized boolean hasCallback(Handler h, Runnable r) { for (Message p = head; p != null; p = p.next) if (p.target == h && p.callback == r && r != null) return true; return false; }
    synchronized boolean hasAny(Handler h) { for (Message p = head; p != null; p = p.next) if (p.target == h) return true; return false; }
    synchronized void quit() { quitting = true; notifyAll(); if (mMain) husk.Native.wake(); }

    // HUSK_FRAME_STATS: the main thread's timed waits, asked for and slept (Looper's line prints them)
    static final boolean STATS = System.getenv("HUSK_FRAME_STATS") != null;
    static long sWaits, sAsked, sSlept, sOver;
    private boolean mNativeLooper;
    private volatile boolean mMain;
    Message next(boolean main) {
        if (main) mMain = true;
        for (;;) {
            if (main) Looper.deliverInput();
            mNativeLooper = husk.Native.nativeLooperPoll();
            long wait;
            synchronized (this) {
                if (quitting) return null;
                long now = SystemClock.uptimeMillis();
                if (head != null && head.when <= now) { Message m = head; head = m.next; m.next = null; return m; }
                if (!main) {
                    wait = head == null ? (mNativeLooper ? 8 : 0) : Math.max(1, mNativeLooper ? Math.min(8, head.when - now) : head.when - now);
                    try { if (wait <= 0) wait(); else wait(wait); } catch (InterruptedException e) { return null; }
                    continue;
                }
                wait = head == null ? -1 : head.when - now;
            }
            // the main thread waits in Husk, where the host's input and other threads' messages (enqueue) wake it at once;
            // Object.wait's timeouts, on Darwin coalesced, overslept by tens of ms and frames and touches waited for them
            long w0 = STATS ? System.nanoTime() : 0;
            husk.Native.waitEvents(wait);
            if (STATS && wait > 0) { long got = System.nanoTime() - w0; sWaits++; sAsked += wait * 1_000_000L; sSlept += got; sOver = Math.max(sOver, got - wait * 1_000_000L); }
        }
    }
